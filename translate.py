def apply_translations(content, translations):
    for jp, zh in translations:
        content = content.replace(jp, zh)
    return content

def translate_file(filepath, translations):
    with open(filepath, 'r', encoding='utf-8') as f:
        original = f.read()
    translated = apply_translations(original, translations)
    if translated != original:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(translated)
        return True
    return False

def main():
    base = 'src/app'
    changed = []

    # HTML templates
    for root, dirs, files in os.walk(base):
        for filename in files:
            if filename.endswith('.html'):
                path = os.path.join(root, filename)
                if translate_file(path, HTML_TRANSLATIONS):
                    changed.append(path)

    # TypeScript component files
    for root, dirs, files in os.walk(os.path.join(base, 'component')):
        for filename in files:
            if filename.endswith('.ts'):
                path = os.path.join(root, filename)
                if translate_file(path, TS_TRANSLATIONS):
                    changed.append(path)

    # TypeScript service files
    for root, dirs, files in os.walk(os.path.join(base, 'service')):
        for filename in files:
            if filename.endswith('.ts'):
                path = os.path.join(root, filename)
                if translate_file(path, TS_TRANSLATIONS):
                    changed.append(path)

    # Class files (default data)
    for root, dirs, files in os.walk(os.path.join(base, 'class')):
        for filename in files:
            if filename.endswith('.ts'):
                path = os.path.join(root, filename)
                # Apply class translations + TS translations, skip comments
                with open(path, 'r', encoding='utf-8') as f:
                    original = f.read()
                translated = apply_translations(original, CLASS_TRANSLATIONS + TS_TRANSLATIONS)
                if translated != original:
                    with open(path, 'w', encoding='utf-8') as f:
                        f.write(translated)
                    changed.append(path)

    # index.html
    index_path = 'src/index.html'
    if os.path.exists(index_path):
        if translate_file(index_path, HTML_TRANSLATIONS + [
            ('ユドナリウム（Udonarium）の私家改造版、高度とかチャットテキストの色とか立ち絵（ユドナリウムだとキャラクターの画像と紛らわしいのでスタンドと呼称）とか。',
             'Udonarium with Fly 繁體中文版，包含高度、聊天文字顏色、立繪（Udonarium稱角色圖片，此處稱為立繪）等功能。')
        ]):
            changed.append(index_path)

    print(f'翻譯完成，共修改 {len(changed)} 個檔案：')
    for f in sorted(changed):
        print(f'  {f}')

if __name__ == '__main__':
    main()
