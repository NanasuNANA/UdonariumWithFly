#!/usr/bin/env node
// Generates static-import registry files for bcdice so that Vite/esbuild
// can statically analyze each import() instead of seeing bare-specifier
// template literals that neither Vite dev server nor browsers can resolve.

import { readdirSync, writeFileSync } from 'fs';

const gameSystemDir = 'node_modules/bcdice/lib/bcdice/game_system';
const i18nDir = 'node_modules/bcdice/lib/bcdice/i18n';
const outDir = 'src/app/class/bcdice';

// --- game systems ---
const classNames = readdirSync(gameSystemDir)
  .filter(f => f.endsWith('.js') && f !== 'index.js')
  .map(f => f.slice(0, -3));

const gameSystemEntries = classNames
  .map(n => `  ['${n}', () => import('bcdice/lib/bcdice/game_system/${n}')]`)
  .join(',\n');

writeFileSync(`${outDir}/bcdice-game-systems.generated.ts`, `\
// AUTO-GENERATED — do not edit manually.
// Regenerated by \`node scripts/generate-bcdice-registry.mjs\` on postinstall.

const gameSystems = new Map<string, () => Promise<unknown>>([
${gameSystemEntries},
]);

export default gameSystems;
`);
console.log(`bcdice registry: ${classNames.length} game systems`);

// --- i18n ---
const i18nKeys = readdirSync(i18nDir)
  .filter(f => f.endsWith('.json') && !f.endsWith('i18n.json'))
  .map(f => f.slice(0, -5)); // strip .json

const i18nEntries = i18nKeys
  .map(k => `  ['${k}', () => import('bcdice/lib/bcdice/i18n/${k}.json')]`)
  .join(',\n');

writeFileSync(`${outDir}/bcdice-i18n.generated.ts`, `\
// AUTO-GENERATED — do not edit manually.
// Regenerated by \`node scripts/generate-bcdice-registry.mjs\` on postinstall.

const i18nSystems = new Map<string, () => Promise<{ default: unknown }>>([
${i18nEntries},
]);

export default i18nSystems;
`);
console.log(`bcdice registry: ${i18nKeys.length} i18n files`);
